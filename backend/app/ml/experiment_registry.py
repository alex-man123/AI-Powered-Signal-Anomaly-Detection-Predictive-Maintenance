"""TASK 8.3 — Experiment Run ID Registry: a unique, persistent, retrievable
identifier for every experiment run, so results can be referenced unambiguously
later (reports, API, frontend) without guessing which configuration produced them.

Blueprint.md section 25 (Reproducibility) already specifies the persistence
mechanism this task formalizes: "Fiecare experiment rulat produce o inregistrare cu:
dataset folosit, strategia de split, configuratie windowing, configuratie
preprocessing, lista de features, model + hiperparametri, threshold-ul folosit,
metricile rezultate, seed. Stocat ca JSON + rand in experiments/experiment_results
(SQLite)." This module IS that "JSON + row in SQLite" mechanism -- one row per
experiment run in a real SQLite table (via TASK 2.1's own `app.core.database`
engine/session infrastructure, not a new database), with the full nested
configuration/metrics stored as JSON text columns.

NOT a second metadata schema: this module has no opinion about what belongs inside
`config`/`metrics` -- both are caller-supplied, opaque, JSON-serializable dicts,
round-tripped byte-for-byte (via `json.dumps`/`json.loads`). It never re-defines
`ModelArtifactMetadata` (TASK 6.5) fields as its own typed columns, and never
recomputes anything TASK 8.1's `evaluate()` already produced -- `metrics` is stored
exactly as given, never recalculated here. A caller building `config` will
typically include things TASK 6.5/8.1 already established (dataset_hash,
split_manifest_hash, model type, threshold method/value, feature_dimension, seed --
see the backlog's own illustrative JSON shape), and MAY simply reference an
existing `ModelArtifactMetadata` sidecar path instead of duplicating its fields --
either way, this registry does not enforce or care about `config`'s internal shape.

RUN ID FORMAT: `EXP-{family}-{NNN}` where `family` is one of `"A"`, `"B"`, `"C"`
(Phase 9's experiment matrix -- raw-vs-DSP-features representations) and `NNN` is a
zero-padded, monotonically increasing sequence number WITHIN that family (`001`,
`002`, ...). The ID is ALWAYS generated by `register_experiment_run` itself, from
the current row count for that family plus one -- there is no parameter through
which a caller can choose or override it, and no use of a timestamp as a substitute
for this format (a timestamp is stored separately, in `created_at`).

Sequence-number assignment is a simple `MAX(sequence) + 1` per family, appropriate
for this project's actual usage pattern (blueprint.md's own rationale for not
introducing MLflow: "sistemul... acopera nevoile unui singur developer care ruleaza
experimente secvential") -- not designed for concurrent multi-writer safety beyond
the database's own UNIQUE constraint on `(family, sequence)`, which turns any actual
collision into an explicit `ExperimentRegistryError` (via the underlying
`IntegrityError`) rather than silently overwriting or duplicating a run.

Persistence: reuses TASK 2.1's own `app.core.database` engine/session machinery
(`get_engine`/`get_session_factory`) -- not a new database. This module's own table
(`experiment_runs`) is created on demand (idempotent `CREATE TABLE IF NOT EXISTS`,
via `checkfirst=True`) the first time `register_experiment_run`/`get_experiment_run`
runs against a given engine, so it works correctly whether or not the caller already
ran `app.core.database.create_schema()` -- no modification to that function was
needed or made.

Determinism vs. uniqueness (explicitly not confused here): a model's own
`random_seed` can make two runs produce IDENTICAL metrics, but each `register_
experiment_run` call still returns a DISTINCT `experiment_id` -- the seed is part of
the opaque `config` payload, never used as or substituted for the run ID itself.

Out of scope (later tasks, not implemented here): Phase 9's actual experiments
(A/B/C matrix runs), the aggregate report (TASK 9.5), any frontend/API wiring
(TASK 11.7) -- this module only guarantees `experiment_id` is available on every
registered run for that future integration to reference.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Any

from sqlalchemy import Engine, String, Text, UniqueConstraint, func, select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Mapped, mapped_column

from app.core.database import Base, get_engine, get_session_factory

VALID_EXPERIMENT_FAMILIES = ("A", "B", "C")


class ExperimentRegistryError(ValueError):
    """Raised for invalid experiment registry input: an unknown `family`, empty
    `config`/`metrics`, a missing `experiment_id` at retrieval, or a genuine
    family/sequence collision at the database level. Never silently corrected --
    no fallback family, no default config/metrics, no silently-overwritten run."""


class ExperimentRun(Base):
    """One row per registered experiment run. `config_json`/`metrics_json` are
    opaque JSON blobs (see module docstring) -- this ORM model defines no typed
    column for anything inside them, deliberately, so it never duplicates TASK
    6.5's `ModelArtifactMetadata` schema or TASK 8.1's metrics shape."""

    __tablename__ = "experiment_runs"

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    experiment_id: Mapped[str] = mapped_column(String(16), unique=True, nullable=False, index=True)
    family: Mapped[str] = mapped_column(String(1), nullable=False)
    sequence: Mapped[int] = mapped_column(nullable=False)
    config_json: Mapped[str] = mapped_column(Text, nullable=False)
    metrics_json: Mapped[str] = mapped_column(Text, nullable=False)
    created_at: Mapped[str] = mapped_column(String(64), nullable=False)

    __table_args__ = (UniqueConstraint("family", "sequence", name="uq_experiment_family_sequence"),)


@dataclass(frozen=True)
class ExperimentRecord:
    """What `get_experiment_run` returns -- the full round-tripped run."""

    experiment_id: str
    config: dict[str, Any]
    metrics: dict[str, Any]
    created_at: str


def _ensure_schema(engine: Engine) -> None:
    """Idempotent: creates `experiment_runs` if it doesn't already exist on this
    engine. Safe to call on every registry operation."""
    ExperimentRun.__table__.create(bind=engine, checkfirst=True)


def _next_sequence(session, family: str) -> int:
    current_max = session.execute(
        select(func.max(ExperimentRun.sequence)).where(ExperimentRun.family == family)
    ).scalar_one()
    return (current_max or 0) + 1


def register_experiment_run(
    family: str,
    config: dict[str, Any],
    metrics: dict[str, Any],
    *,
    engine: Engine | None = None,
) -> str:
    """Registers one experiment run and returns its automatically-generated,
    unique `experiment_id`.

    Args:
        family: `"A"`, `"B"`, or `"C"` -- Phase 9's experiment matrix family this
            run belongs to.
        config: the full configuration that produced this run -- opaque to this
            function (never validated/typed beyond "non-empty dict"; see module
            docstring for the illustrative shape the backlog suggests, e.g.
            `dataset_hash`/`split_manifest_hash`/`representation`/`model`/
            `feature_dimension`/`random_seed`/`preprocessing_config`/
            `model_config`/`threshold`). Must be JSON-serializable.
        metrics: the evaluation metrics for this run -- typically TASK 8.1's
            `app.ml.evaluation.evaluate()` output, passed through UNCHANGED (never
            recomputed here). Must be JSON-serializable.
        engine: SQLAlchemy engine to use; defaults to this project's shared
            `app.core.database.get_engine()`. Exposed mainly for test isolation.

    Returns:
        The new run's `experiment_id`, format `EXP-{family}-{NNN}` (e.g.
        `"EXP-A-001"`) -- generated here, never chosen by the caller.

    Raises:
        ExperimentRegistryError: if `family` is not one of `"A"`/`"B"`/`"C"`, if
            `config`/`metrics` is empty, or if a genuine family/sequence
            collision occurs at the database level.
    """
    if family not in VALID_EXPERIMENT_FAMILIES:
        raise ExperimentRegistryError(
            f"family must be one of {VALID_EXPERIMENT_FAMILIES}, got {family!r}"
        )
    if not config:
        raise ExperimentRegistryError("config must not be empty")
    if not metrics:
        raise ExperimentRegistryError("metrics must not be empty")

    try:
        config_json = json.dumps(config)
        metrics_json = json.dumps(metrics)
    except TypeError as exc:
        raise ExperimentRegistryError(f"config/metrics must be JSON-serializable: {exc}") from exc

    resolved_engine = engine or get_engine()
    _ensure_schema(resolved_engine)
    session_factory = get_session_factory(resolved_engine)

    created_at = datetime.now(timezone.utc).isoformat()

    with session_factory() as session:
        sequence = _next_sequence(session, family)
        experiment_id = f"EXP-{family}-{sequence:03d}"

        run = ExperimentRun(
            experiment_id=experiment_id,
            family=family,
            sequence=sequence,
            config_json=config_json,
            metrics_json=metrics_json,
            created_at=created_at,
        )
        session.add(run)
        try:
            session.commit()
        except IntegrityError as exc:
            session.rollback()
            raise ExperimentRegistryError(
                f"experiment_id/sequence collision registering family={family!r} "
                f"at sequence={sequence}: {exc}"
            ) from exc

    return experiment_id


def get_experiment_run(experiment_id: str, *, engine: Engine | None = None) -> ExperimentRecord:
    """Retrieves a previously registered experiment run by its `experiment_id`.

    Args:
        experiment_id: e.g. `"EXP-A-001"`, as returned by `register_experiment_run`.
        engine: SQLAlchemy engine to use; defaults to this project's shared
            `app.core.database.get_engine()`.

    Returns:
        An `ExperimentRecord` with `config`/`metrics` identical to what was
        registered (round-tripped through JSON, not re-derived or recomputed).

    Raises:
        ExperimentRegistryError: if `experiment_id` is empty or no run with that
            ID exists.
    """
    if not experiment_id:
        raise ExperimentRegistryError("experiment_id must not be empty")

    resolved_engine = engine or get_engine()
    _ensure_schema(resolved_engine)
    session_factory = get_session_factory(resolved_engine)

    with session_factory() as session:
        run = session.execute(
            select(ExperimentRun).where(ExperimentRun.experiment_id == experiment_id)
        ).scalar_one_or_none()

    if run is None:
        raise ExperimentRegistryError(f"No experiment run found for experiment_id={experiment_id!r}")

    return ExperimentRecord(
        experiment_id=run.experiment_id,
        config=json.loads(run.config_json),
        metrics=json.loads(run.metrics_json),
        created_at=run.created_at,
    )
